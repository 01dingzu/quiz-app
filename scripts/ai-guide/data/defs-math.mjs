// 与 408 三科 defs 的差异，刻意为之：
//
// 1. math.json 的 subject 是按「题号段」硬分的，约 30 道线代/概率题被标成
//    「高等数学」（如 math-2010-05 是矩阵秩、math-2010-07 是分布函数）。
//    若按 subject 分科建资源，这些题会拿到错误学科的知识点。
//    因此本文件产出**一份三科共享资源**：kg / mothers / tags 都含三科全量，
//    guide.ts 的三行 RESOURCES 全部指向同一份文件。
//    每题的 topic / mt 按题干实际考点人工指定，与题库 subject 无关。
//
// 2. 不写关键词规则。数学题干以 LaTeX 为主（\frac \int \lim \pmatrix …），
//    中文关键词被公式切碎，tag.mjs 的打分门槛会产生大量漏标与歧义；
//    219 道题全部走人工 override，by 一律为 'override'，可逐条复核。
//
// 3. 不生成干扰项诊断与解析体检警示：数学选项是公式、解析是 LaTeX，
//    408 那套「按选项字母 + 解析原文逐字锚定」不适用，不编造引用。
//
// 依据：数学一考试大纲章节体系 + 2010–2025 客观题 219 道真题考点分布。
// 由 4-build-math.mjs 消费，产出 public/guide/*-math.json。
// ============================================================

const N = (id, name, chapter, prereq, summary, keywords, weight) =>
  ({ id, name, chapter, prereq, summary, keywords, weight })

const M = (id, name, topics, skeleton, traps) => ({
  id, name, topics, skeleton,
  traps: Object.fromEntries(traps.map((label, i) => [`t${i + 1}`, { label }])),
})

/** 把「母题 → 题号列表」展开成逐题人工标注表 */
function overrides(groups) {
  const out = {}
  for (const [mt, topic, ids] of groups) {
    for (const raw of ids.trim().split(/\s+/)) {
      if (!raw) continue
      const qid = 'math-' + raw
      if (out[qid]) throw new Error(`题号重复标注：${qid}（${out[qid].mt} 与 ${mt}）`)
      out[qid] = { mt, topic, note: '按题干实际考点人工逐题标注' }
    }
  }
  return out
}

