//    一样只产出**一份六科共享资源**，guide.ts 里六行 RESOURCES 指向同一组文件，
//    每题的 topic / mt 按题干实际考点挂载，与题库 subject 无关。
//
// 2. 政治是背诵辨析型，不是解题型。Mother.skeleton 在这里不叫「解题步骤」，
//    而是「命题角度 → 定位原理 → 排除陷阱 → 回代材料」的判断流程；traps 是
//    绝对化表述、张冠李戴、时间错位、以偏概全这类高频干扰项。不照搬 408 的
//    计算型四步骨架，也不生成按选项字母逐字锚定的干扰项诊断。
//
// 3. 589 题走「全局关键词打分 + 人工 override 兜底」：政治题干是纯中文、概念词
//    明确，规则命中率远高于 LaTeX 题干的数学；构建脚本会输出每题的 topic/mt/by，
