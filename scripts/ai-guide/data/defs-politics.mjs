/** 按题干实际考点给一题分配 { topic, mt, by, score }；不读 q.subject */
export function assignQuestion(q) {
  const ov = POLITICS_OVERRIDES[q.id]
  if (ov) return { topic: ov.topic, mt: ov.mt, by: 'override', score: 999 }

  // 解析里的「本题考查的考点是：X /【考点点拨】/【考点】」是最可靠的考点信号；
  // 真题材料常含跨科干扰词（如爱国主义题里提到「鸦片战争」），故解析权重高于题干。
  const expl = q.explanation || ''
  const focus = [
    /本题考查的考点是[:：]\s*([^。；\n【]+)/.exec(expl)?.[1],
    /【考点点拨】\s*([^。；\n【]+)/.exec(expl)?.[1],
    /【考点】\s*([^\n]+)/.exec(expl)?.[1],
  ].filter(Boolean).join(' ')
  const primary = expl.slice(0, 220)
  const secondary = (q.stem || '') + ' ' + Object.values(q.options || {}).join(' ')

  // 科目前验 + 跨科泛词抑制：
  // 马原规则里的「发展 / 联系 / 矛盾 / 实践」这类泛词在别科解析正文中几乎每题都有，
  // 若照常加权会把毛中特、史纲、时政题大量抢到马原「三大规律」。因此：
  //   · 同科规则：考点名 +6、解析正文 +3、题干选项 +1，并加 18 分先验；
  //   · 跨科规则：只有命中「考点名」才计 +6，解析正文的泛词一律不计分，
  //     题干选项仍 +1 —— 跨科必须由明确的考点名驱动，不能靠正文里的泛词。
  // 这样 no11/12 那批被硬分成「史纲」的思修题仍能被「道德的作用」正确拉回思修。
  const subjCode = SUBJECT_CODE[q.subject] || ''
  let best = null
  let bestScore = -1
  for (const r of RULES) {
    const sameSubject = subjCode ? r.topic.startsWith(subjCode + '-') : false
    const crossToMy = !sameSubject && r.topic.startsWith('my-')
    if (crossToMy && GENERIC_MY_NODES.has(r.topic)) continue
    let hits = 0
    for (const k of r.kw) {
      if (crossToMy && GENERIC_MY.has(k)) continue
      if (focus.includes(k)) hits += 6
      else if (sameSubject && primary.includes(k)) hits += 3
      if (secondary.includes(k)) hits += 1
    }
    if (hits === 0) continue
    const score = hits * 10 + r.w + (sameSubject ? 18 : 0)
    if (score > bestScore) { bestScore = score; best = r }
  }

  const type = q.type === 'multi' ? 'multi' : q.type === 'applied' ? 'applied' : 'single'
  if (!best) {
    const fb = FALLBACK_BY_SUBJECT[q.subject]
    if (!fb) return { topic: null, mt: null, by: 'fallback', score: 0 }
    return { topic: fb.topic, mt: fb[type], by: 'default', score: 0 }
  }
  return { topic: best.topic, mt: best.mt[type] || best.mt.single, by: 'rule', score: bestScore }
}
