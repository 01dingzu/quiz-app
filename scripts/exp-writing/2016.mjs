/** 本批无采集错误需要修正；答案字母一律不动 */
const PATCHES = {}

const questions = JSON.parse(fs.readFileSync(QFILE, 'utf8'))
const targets = questions.filter((q) => q.id.startsWith(YEAR) && SUBJECTS.has(q.subject))
const ids = new Set(targets.map((q) => q.id))
const missingKeys = Object.keys(EXPLANATIONS).filter((k) => !ids.has(k))
const missingExpl = [...ids].filter((k) => !EXPLANATIONS[k])
const badPatches = Object.keys(PATCHES).filter((k) => !ids.has(k))
if (missingKeys.length || missingExpl.length || badPatches.length) {
  console.error('ID 不匹配。脚本里有但库里无：', missingKeys, badPatches)
  console.error('库里有但脚本里无：', missingExpl)
  process.exit(1)
}

const answerBefore = new Map(targets.map((q) => [q.id, q.answer]))
const backup = path.join(os.tmpdir(), `questions-2016-backup-${Date.now()}.json`)
fs.writeFileSync(backup, JSON.stringify(questions), 'utf8')

let filled = 0
let patched = 0
for (const q of questions) {
  if (ids.has(q.id) && EXPLANATIONS[q.id]) {
    q.explanation = EXPLANATIONS[q.id]
    filled++
  }
  const p = PATCHES[q.id]
  if (p) {
    if (p.stem) q.stem = p.stem
    if (p.options) q.options = p.options
    patched++
  }
}
fs.writeFileSync(QFILE, JSON.stringify(questions), 'utf8')

const lens = Object.values(EXPLANATIONS).map((s) => s.length).sort((a, b) => a - b)
console.log(`2016 年待补题数: ${targets.length}`)
