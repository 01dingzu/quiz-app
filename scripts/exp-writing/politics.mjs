// 校验 + 备份 + 写入
// ---------------------------------------------------------------

const raw = fs.readFileSync(BANK, 'utf8')
const arr = JSON.parse(raw)
if (!Array.isArray(arr)) throw new Error('politics.json 顶层不是数组，脚本中止')
const byId = new Map(arr.map((q) => [q.id, q]))

console.log(`政治题库 ${arr.length} 题，待补 ${Object.keys(EXPLANATIONS).length} 道\n`)

let fatal = false
for (const [id, text] of Object.entries(EXPLANATIONS)) {
  const q = byId.get(id)
  if (!q) {
    console.error(`  ✗ 找不到题目 ${id}`)
    fatal = true
    continue
  }
  // 富文本安全自检
  if (/[<>$]|\*\*|\\(frac|sqrt|times|cdot|text|begin)/.test(text)) {
    console.error(`  ✗ ${id} 含富文本风险字符（裸尖括号 / $ / LaTeX 命令 / Markdown 加粗）`)
    fatal = true
  }
  const before = q.explanation || ''
  console.log(
    `  ${id}  ${String(before.length).padStart(3)} → ${String(text.length).padStart(3)} 字  原值：${JSON.stringify(before.slice(0, 14))}`,
  )
}
if (fatal) {
  console.error('\n✗ 校验未通过，未写入任何内容')
  process.exit(1)
}

const backup = path.join(os.tmpdir(), `politics-exp-backup-${Date.now()}.json`)
fs.writeFileSync(backup, raw, 'utf8')

for (const [id, text] of Object.entries(EXPLANATIONS)) byId.get(id).explanation = text
fs.writeFileSync(BANK, `${JSON.stringify(arr, null, 1)}\n`, 'utf8')

console.log(`\n✓ 已写入 ${Object.keys(EXPLANATIONS).length} 道解析`)
console.log(`✓ 备份：${backup}`)
